#!/usr/bin/env node
// Runs every local check for D:\icarus.
// Usage: node scripts/check.mjs
// Steps: dash check on added lines and workspace docs, attribution check, Jest unit tests, offline INARA scraper tests, Next.js client build.
// Prints "CHECK PASSED" on success, or "CHECK FAILED: <step>" and exits 1.
const { execSync, spawnSync } = require('child_process')
const { existsSync, readFileSync } = require('fs')

const DASH_CHARS = String.fromCodePoint(0x2013, 0x2014, 0x2015)
const DASHES = new RegExp(
  `[${DASH_CHARS}]|&(?:mdash|ndash|#8212|#8211|#8213|#x2014|#x2013|#x2015);|\\\\u201[345]|\\x20--\\x20`,
  'i'
)
const ATTRIBUTION = /Co-Authored-By|Generated with|Generated by|\/session/i

function fail (step) {
  console.log(`CHECK FAILED: ${step}`)
  process.exit(1)
}

function git (args) {
  return execSync(`git ${args}`, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
}

function run (step, command, env = {}) {
  console.log(`==> ${step}...`)
  const result = spawnSync(command, {
    shell: true,
    stdio: 'inherit',
    env: { ...process.env, NEXT_TELEMETRY_DISABLED: '1', FORCE_MOCK_DATA: 'true', ...env }
  })
  if (result.status !== 0) fail(step)
}

console.log('==> Checking added lines for em dashes and en dashes...')
let base = 'origin/main'
try {
  git(`rev-parse --verify ${base}`)
} catch (e) {
  base = 'HEAD'
}
const diff = git(`diff ${base}...HEAD`) + git('diff HEAD')
const badDiffLines = diff
  .split(/\r?\n/)
  .filter(line => line.startsWith('+') && !line.startsWith('+++') && DASHES.test(line))
if (badDiffLines.length > 0) {
  for (const line of badDiffLines) console.log(`  ${line}`)
  fail('dashes (diff)')
}

console.log('==> Checking workspace orchestration files for dashes...')
const DOC_FILES = [
  'AGENTS.md',
  'GEMINI.md',
  'WORKFLOW.md',
  'history/STATE.md',
  'history/DECISIONS.md',
  'testing/README.md'
]
let docFailed = false
for (const file of DOC_FILES) {
  if (!existsSync(file)) continue
  const lines = readFileSync(file, 'utf8').split(/\r?\n/)
  for (let i = 0; i < lines.length; i++) {
    const stripped = lines[i].replace(/`[^`]*`/g, '')
    if (DASHES.test(stripped)) {
      console.log(`  ${file}:${i + 1}: ${lines[i]}`)
      docFailed = true
    }
  }
}
if (docFailed) fail('dashes (docs)')

console.log('==> Checking recent commit messages for tool attribution...')
try {
  const logOut = git(`log ${base}..HEAD --format=%B`)
  if (ATTRIBUTION.test(logOut)) {
    console.log('  Prohibited attribution found in commit log.')
    fail('attribution')
  }
} catch (e) {
  // ignore when base equals HEAD
}

run('Jest unit & API tests (npm test)', 'npm test -- --runInBand --config jest.config.js')
run('Offline INARA scraper suite (npm run test:scrapers)', 'npm run test:scrapers')
run('Next.js client static export build (npm run build:client)', 'npm run build:client')

console.log('CHECK PASSED')
